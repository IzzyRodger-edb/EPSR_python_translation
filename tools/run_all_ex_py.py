#!/usr/bin/env python3
"""Run several test cases (tools/run_ex_py.py) in parallel and summarise them.

usage: tools/run_all_ex_py.py [CASE ...] [--jobs N] [--mode resume|chain] [--work DIR]
                              [--programs epsr,nwts] [--out results.md]

With no CASE, every test_problems/200DMSO400Water/EPSR-test-ex* folder is run.
``--programs`` keeps only cases whose commands use nothing but those programs (useful
while only some programs are translated).  Writes a Markdown table (default
docs/ex_results.md) with one row per case: steps identical / total, Fortran and Python
time, slowdown.
"""

import argparse
import concurrent.futures as cf
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CASES = os.path.join(ROOT, "test_problems", "200DMSO400Water")


def programs_of(case):
    progs = set()
    with open(os.path.join(case, "commands.txt")) as fh:
        for ln in fh:
            ln = ln.split("#", 1)[0].strip()
            if ln and not ln.startswith("repeat"):
                progs.add(ln.split()[0])
    return progs


def run_case(case, work, mode, timeout):
    name = os.path.basename(case)
    w = os.path.join(work, name)
    p = subprocess.run([sys.executable, os.path.join(HERE, "run_ex_py.py"), case, "--work", w, "--mode", mode,
                        "--timeout", str(timeout)], capture_output=True, text=True)
    try:
        with open(os.path.join(w, "summary.json")) as fh:
            summ = json.load(fh)
    except OSError:
        summ = {"steps": [], "error": p.stdout[-2000:] + p.stderr[-2000:]}
    summ["name"] = name
    summ["stdout"] = p.stdout
    return summ


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cases", nargs="*")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) - 2))
    ap.add_argument("--mode", default="resume")
    ap.add_argument("--work", default=os.path.join(ROOT, "work", "ex"))
    ap.add_argument("--programs")
    ap.add_argument("--timeout", type=float, default=36000)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "ex_results.md"))
    a = ap.parse_args()
    cases = [os.path.abspath(c) for c in a.cases] or sorted(
        (os.path.join(CASES, d) for d in os.listdir(CASES) if d.startswith("EPSR-test-ex")),
        key=lambda s: int(re.sub(r"\D", "", os.path.basename(s)) or 0))
    if a.programs:
        allowed = set(a.programs.split(","))
        cases = [c for c in cases if programs_of(c) <= allowed]
    os.makedirs(a.work, exist_ok=True)
    rows = []
    with cf.ProcessPoolExecutor(max_workers=a.jobs) as ex:
        futs = {ex.submit(run_case, c, a.work, a.mode, a.timeout): c for c in cases}
        for f in cf.as_completed(futs):
            s = f.result()
            steps = [x for x in s["steps"] if "identical" in x]
            nid = sum(1 for x in steps if x["identical"])
            ft = sum(x["fortran_s"] for x in steps)
            pt = sum(x.get("python_s", 0) for x in steps)
            rows.append((s["name"], nid, len(steps), ft, pt, ",".join(sorted({x["program"] for x in s["steps"]}))))
            print(f"{s['name']:20s} {nid}/{len(steps)} identical  fortran {ft:7.1f} s  python {pt:8.1f} s", flush=True)
    rows.sort(key=lambda r: int(re.sub(r"\D", "", r[0]) or 0))
    lines = ["# Test-problem results (generated by tools/run_all_ex_py.py)", "",
             f"Mode: {a.mode}. A step is identical when every file matches the Fortran byte for byte",
             "(date in .out and fort.35 timings masked).", "",
             "| case | programs | identical steps | Fortran [s] | Python [s] | slowdown |", "|---|---|---:|---:|---:|---:|"]
    for name, nid, n, ft, pt, progs in rows:
        sl = f"{pt / ft:.0f}x" if ft > 0 and pt > 0 else ""
        lines.append(f"| {name} | {progs} | {nid}/{n} | {ft:.1f} | {pt:.1f} | {sl} |")
    tot = sum(r[1] for r in rows), sum(r[2] for r in rows)
    lines += ["", f"Total: {tot[0]}/{tot[1]} steps identical in {len(rows)} cases."]
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
