#!/usr/bin/env python3
"""Index of every Fortran routine and its Python translation -> docs/ROUTINE_INDEX.md.

The Python side is found from the docstrings, which start with ``<file>:<routine>``
(TRANSLATION_GUIDE section 1); the Fortran side from tools/gen/gen_signatures.py.
Routines of the active Fortran sources with no Python counterpart are listed at the end.
"""

import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import gen_signatures as gs  # noqa: E402

PKG = os.path.join(ROOT, "src", "epsr26")
DOC = re.compile(r"^\s*([A-Za-z0-9_\-]+\.f(?:90)?)\s*:\s*([A-Za-z0-9_]+)")


def python_routines():
    found = {}
    for dirpath, _, files in os.walk(PKG):
        for f in sorted(files):
            if not f.endswith(".py"):
                continue
            path = os.path.join(dirpath, f)
            rel = os.path.relpath(path, os.path.join(ROOT, "src"))
            tree = ast.parse(open(path).read())
            for node in ast.walk(tree):
                if isinstance(node, ast.FunctionDef):
                    doc = ast.get_docstring(node) or ""
                    m = DOC.match(doc)
                    if m:
                        key = (m.group(1), m.group(2).lower())
                        found.setdefault(key, []).append((rel, node.name, node.lineno))
    return found


def main():
    files = [ln.strip() for ln in open(os.path.join(gs.SRC, "ACTIVE_SOURCES.txt")) if ln.strip() and not ln.startswith("#")]
    units = []
    for f in files:
        p = os.path.join(gs.SRC, f)
        if os.path.exists(p):
            units += gs.parse_units(p)
    py = python_routines()
    lines = ["# Routine index (generated by tools/gen/gen_routine_index.py)", "",
             "Every routine of the active Fortran sources and the Python function that translates it.",
             "Programs (`program standalone` etc.) are the `main()` of the module in `programs/`.", ""]
    missing = []
    cur = None
    n_done = 0
    for u in units:
        if u.file != cur:
            cur = u.file
            lines += ["", f"## {cur}", "", "| Fortran | line | Python |", "|---|---:|---|"]
        hits = py.get((u.file, u.name), [])
        if u.kind == "program":
            hits = hits or [(r, n, ln) for (ff, _), v in py.items() if ff == u.file for (r, n, ln) in v if n == "main"]
        if hits:
            n_done += 1
            where = "<br>".join(f"`{r}:{ln}` `{n}`" for r, n, ln in hits)
        else:
            where = "**not found**"
            missing.append(f"{u.file}:{u.line} {u.kind} {u.name}")
        kind = "" if u.kind == "subroutine" else f"{u.kind} "
        lines.append(f"| {kind}`{u.name}` | {u.line} | {where} |")
    lines[4:4] = [f"Translated: {n_done} of {len(units)} routines.", ""]
    if missing:
        lines += ["", "## Not found", "", "No Python docstring names these routines (an interface block, a",
                  "duplicate, or not translated):", ""] + [f"- {m}" for m in missing]
    with open(os.path.join(ROOT, "docs", "ROUTINE_INDEX.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"{n_done}/{len(units)} routines indexed; {len(missing)} not found")


if __name__ == "__main__":
    main()
